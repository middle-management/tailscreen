def packetize_h264(nals, ts, ssrc, start_seq):
    """TS-VID-031 / TS-VID-032."""
    packets = []
    seq = start_seq
    for nal in nals:
        if not nal:
            continue
        if len(nal) <= MAX_RTP_PAYLOAD:
            packets.append(rtp_header(False, H264_PT, seq, ts, ssrc) + nal)
            seq = (seq + 1) & 0xFFFF
            continue
        nal_header = nal[0]
        fu_indicator = (nal_header & 0x60) | 28
        nal_type = nal_header & 0x1F
        body = nal[1:]
        frag = MAX_RTP_PAYLOAD - 2
        off, first = 0, True
        while off < len(body):
            take = min(frag, len(body) - off)
            last = off + take == len(body)
            fu_header = nal_type | (0x80 if first else 0) | (0x40 if last else 0)
            packets.append(
                rtp_header(False, H264_PT, seq, ts, ssrc)
                + bytes([fu_indicator, fu_header])
                + body[off : off + take]
            )
            seq = (seq + 1) & 0xFFFF
            off += take
            first = False
    if packets:
        packets[-1] = set_marker(packets[-1])  # TS-VID-006
    return packets


def packetize_hevc(nals, ts, ssrc, start_seq):
    """TS-VID-033 / TS-VID-036."""
    packets = []
    seq = start_seq
    for nal in nals:
        if len(nal) < 2:
            continue
        if len(nal) <= MAX_RTP_PAYLOAD:
            packets.append(rtp_header(False, HEVC_PT, seq, ts, ssrc) + nal)
            seq = (seq + 1) & 0xFFFF
            continue
        nh0, nh1 = nal[0], nal[1]
        original_type = (nh0 >> 1) & 0x3F
        payload_hdr0 = (nh0 & 0x80) | (49 << 1) | (nh0 & 0x01)
        payload_hdr1 = nh1
        body = nal[2:]
        frag = MAX_RTP_PAYLOAD - 3
        off, first = 0, True
        while off < len(body):
            take = min(frag, len(body) - off)
            last = off + take == len(body)
            fu_header = (original_type & 0x3F) | (0x80 if first else 0) | (0x40 if last else 0)
            packets.append(
                rtp_header(False, HEVC_PT, seq, ts, ssrc)
                + bytes([payload_hdr0, payload_hdr1, fu_header])
                + body[off : off + take]
            )
            seq = (seq + 1) & 0xFFFF
            off += take
            first = False
    if packets:
        packets[-1] = set_marker(packets[-1])
    return packets


def set_marker(packet: bytes) -> bytes:
    return packet[:1] + bytes([packet[1] | 0x80]) + packet[2:]


def parity_body(packets):
    """TS-FEC (§9.3): XOR of [len:2][byte1][timestamp:4][payload...]."""
    if len(packets) < 2:
        return b""
    if any(len(p) < 12 for p in packets):
        return b""
    max_len = max(len(p) for p in packets)
    body = bytearray(7 + (max_len - 12))
    for p in packets:
        body[0] ^= (len(p) >> 8) & 0xFF
        body[1] ^= len(p) & 0xFF
        body[2] ^= p[1]
        for i in range(4):
            body[3 + i] ^= p[4 + i]
        for i in range(len(p) - 12):
            body[7 + i] ^= p[12 + i]
    return bytes(body)


def fec_recover(missing_seq, ssrc, members, body):
    """TS-FEC-009 / TS-FEC-010."""
    if len(body) < 7:
        return None
    if any(len(m) < 12 for m in members):
        return None
    if any(len(m) - 12 > len(body) - 7 for m in members):
        return None
    solved = bytearray(body)
    for m in members:
        solved[0] ^= (len(m) >> 8) & 0xFF
        solved[1] ^= len(m) & 0xFF
        solved[2] ^= m[1]
        for i in range(4):
            solved[3 + i] ^= m[4 + i]
        for i in range(len(m) - 12):
            solved[7 + i] ^= m[12 + i]
    recovered_len = int.from_bytes(solved[0:2], "big")
    if recovered_len < 12 or recovered_len - 12 > len(solved) - 7:
        return None
    out = bytearray()
    out.append(0x80)
    out.append(solved[2])
    out += be16(missing_seq)
    out += solved[3:7]
    out += be32(ssrc)
    out += solved[7 : 7 + (recovered_len - 12)]
    return bytes(out)


