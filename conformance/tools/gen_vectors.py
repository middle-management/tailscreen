def h(b: bytes) -> str:
    return b.hex()


def be16(v: int) -> bytes:
    return v.to_bytes(2, "big")


def be32(v: int) -> bytes:
    return v.to_bytes(4, "big")


def be64(v: int) -> bytes:
    return v.to_bytes(8, "big")


def rtp_header(marker: bool, pt: int, seq: int, ts: int, ssrc: int) -> bytes:
    """TS-VID-001: V=2, P=0, X=0, CC=0."""
    return bytes([0x80, (0x80 if marker else 0x00) | (pt & 0x7F)]) + be16(seq) + be32(ts) + be32(ssrc)


def filler(n: int, salt: int = 0) -> bytes:
    """Deterministic, non-repeating-ish payload bytes for the long vectors."""
    return bytes(((i * 7 + salt * 31 + 3) & 0xFF) for i in range(n))


