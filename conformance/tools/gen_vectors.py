def main():
    os.makedirs(OUT, exist_ok=True)
    index = []
    for suite in SUITES:
        ids = [c["id"] for c in suite["cases"]]
        assert len(ids) == len(set(ids)), f"duplicate case id in {suite['suite']}"
        path = os.path.join(OUT, suite["suite"] + ".json")
        with open(path, "w") as f:
            json.dump(suite, f, indent=2, sort_keys=False)
            f.write("\n")
        index.append({"suite": suite["suite"], "file": suite["suite"] + ".json", "cases": len(ids)})
        print(f"{path}: {len(ids)} cases")

    with open(os.path.join(OUT, "index.json"), "w") as f:
        json.dump(
            {
                "specVersion": 1,
                "spec": "docs/spec.md",
                "generator": "conformance/tools/gen_vectors.py",
                "suites": index,
            },
            f,
            indent=2,
        )
        f.write("\n")
    print(f"total: {sum(s['cases'] for s in index)} cases")


if __name__ == "__main__":
    main()
