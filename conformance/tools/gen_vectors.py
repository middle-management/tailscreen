#!/usr/bin/env python3
"""Regenerate the conformance vectors under ../vectors.

The vectors are checked in — this script exists so they are reproducible and
so a bulk edit (a new field, a renamed op) is a one-line change rather than a
hand-edit of several thousand hex characters. Run it from anywhere:

    python3 conformance/tools/gen_vectors.py

then re-run the Go suite (`make test-conformance`) and, on a machine with a
Swift toolchain, `make test-protocol` — the two runners are what actually
decide whether the regenerated bytes are right.

Every literal in here traces to a requirement in docs/spec.md. This file is
NOT a third implementation of the protocol to be consulted at runtime: it is
a fixture builder, and the Go and Swift runners are the implementations under
test.
"""

